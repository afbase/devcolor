'use strict';

/** Parse a Cookie header into a plain object. No dependency needed. */
function parseCookies(req) {
  const out = {};
  for (const part of (req.headers.cookie || '').split(';')) {
    const i = part.indexOf('=');
    if (i < 0) continue;
    out[part.slice(0, i).trim()] = decodeURIComponent(part.slice(i + 1).trim());
  }
  return out;
}

/**
 * A05: contextual output encoding for HTML text nodes. This stops reflected and
 * stored XSS. NOT sufficient inside <script>, href="", or on* attributes.
 */
function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;').replaceAll("'", '&#39;');
}

module.exports = { parseCookies, escapeHtml };
